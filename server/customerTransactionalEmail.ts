function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function replaceTemplateVariables(
  content: string,
  allowedVariables: string[],
  variables: Record<string, string>,
  escapeValues: boolean,
): string {
  const allowed = new Set(allowedVariables);
  return content.replace(/\{\{\s*([a-zA-Z0-9_]+)\s*\}\}/g, (_match, key: string) => {
    if (!allowed.has(key)) return "";
    const value = variables[key] || "";
    return escapeValues ? escapeHtml(value) : value;
  });
}

export function renderCustomerEmailTemplate(
  template: TemplateContent,
  variables: Record<string, string>,
): { subject: string; html: string; text: string } {
  const safeSubjectVariables = Object.fromEntries(
    Object.entries(variables).map(([key, value]) => [
      key,
      String(value || "").replace(/[\r\n]+/g, " ").replace(/[\x00-\x1f\x7f]/g, ""),
    ]),
  );
  return {
    subject: replaceTemplateVariables(template.subject, template.variables, safeSubjectVariables, false),
    html: replaceTemplateVariables(template.htmlContent, template.variables, variables, true),
    text: replaceTemplateVariables(template.textContent, template.variables, variables, false),
  };
}

export function renderCustomerEmailTemplatePreview(
  template: TemplateContent,
): { subject: string; html: string; text: string } {
  return renderCustomerEmailTemplate(template, PREVIEW_VALUES);
}

export async function ensureCustomerEmailTemplateDefaults(): Promise<void> {
  await db.insert(transactionalEmailTemplates)
    .values(CUSTOMER_EMAIL_TEMPLATE_DEFAULTS.map((template) => ({
      ...template,
    })))
    .onConflictDoNothing({ target: transactionalEmailTemplates.templateKey });
}

export async function getCustomerEmailTemplateForDelivery(
  templateKey: "customer_welcome" | "customer_password_reset",
): Promise<TemplateContent> {
  const [stored] = await db.select()
    .from(transactionalEmailTemplates)
    .where(and(
      eq(transactionalEmailTemplates.templateKey, templateKey),
      eq(transactionalEmailTemplates.status, "active"),
    ))
    .limit(1);
  return stored || DEFAULTS_BY_KEY.get(templateKey)!;
}

export async function sendCustomerTransactionalEmail(input: {
  templateKey: "customer_welcome" | "customer_password_reset";
  to: string;
  variables: Record<string, string>;
}): Promise<boolean> {
  try {
    const configs = await storage.getUserEmailConfigs();
    const connectedConfig = configs.find((config) =>
      config.isConnected &&
      config.titanAppPasswordEncrypted &&
      config.companyEmail === "admin@bright-organic.com",
    ) || configs.find((config) => config.isConnected && config.titanAppPasswordEncrypted);

    if (!connectedConfig?.titanAppPasswordEncrypted || !connectedConfig.companyEmail) {
      console.warn(`[Customer Email] ${input.templateKey} skipped: no connected sender`);
      return false;
    }

    const template = await getCustomerEmailTemplateForDelivery(input.templateKey);
    const rendered = renderCustomerEmailTemplate(template, input.variables);
    await titanEmailProvider.send({
      email: connectedConfig.companyEmail,
      encryptedAppPassword: connectedConfig.titanAppPasswordEncrypted,
    }, {
      to: [input.to],
      subject: rendered.subject,
      bodyHtml: rendered.html,
      bodyText: rendered.text,
      fromName: "Atlas Ingredients",
    });
    return true;
  } catch (error) {
    console.error(
      `[Customer Email] ${input.templateKey} delivery failed:`,
      error instanceof Error ? error.name : "Unknown delivery error",
    );
    return false;
  }
}
